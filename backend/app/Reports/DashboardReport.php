<?php

namespace App\Reports;

use App\Enums\EquipmentOperation;
use App\Enums\EquipmentUtilization;
use App\Models\User;
use OpenSpout\Common\Entity\Row;
use OpenSpout\Common\Entity\Style\Style;
use OpenSpout\Writer\XLSX\Entity\SheetView;
use OpenSpout\Writer\XLSX\Writer;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * The data behind every Dashboard chart as an Excel workbook, one sheet per chart, in the
 * Dashboard's order. Numbers come from DashboardSummary, so they always match the charts.
 */
class DashboardReport
{
    /** @var array<string, mixed> */
    private array $data;

    private string $timezone;

    public function __construct(private User $user)
    {
        $this->data = DashboardSummary::build();
        $this->timezone = config('fic.timezone');
    }

    public function download(): StreamedResponse
    {
        $filename = 'onefic-dashboard-data-'.now($this->timezone)->format('Y-m-d-His').'.xlsx';

        return response()->streamDownload(
            fn () => $this->writeTo('php://output'),
            $filename,
            ['Content-Type' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'],
        );
    }

    public function writeTo(string $path): void
    {
        $writer = new Writer;
        $writer->openToFile($path);

        $sheets = [
            'Overview' => $this->overview(...),
            'FICs and products' => $this->ficsAndProducts(...),
            'Food MSME partners' => $this->msmePartners(...),
            'Assistance nationwide' => $this->assistanceNationwide(...),
            'Assistance by region' => $this->assistanceByRegion(...),
            'Equipment by region' => $this->equipmentByRegion(...),
            'Equipment by type' => $this->equipmentByType(...),
        ];

        $first = true;
        foreach ($sheets as $name => $write) {
            ($first ? $writer->getCurrentSheet() : $writer->addNewSheetAndMakeItCurrent())->setName($name);
            $write($writer);
            $first = false;
        }

        $writer->close();
    }

    private function overview(Writer $writer): void
    {
        $national = $this->data['national'];
        $writer->getCurrentSheet()->setColumnWidth(42, 1);
        $writer->getCurrentSheet()->setColumnWidth(18, 2);

        $writer->addRow(Row::fromValuesWithStyle([config('app.name').': Dashboard data'], new Style(fontBold: true, fontSize: 14, fontColor: EntryReport::BRAND_GREEN)));
        $writer->addRow(Row::fromValues(['Generated', now($this->timezone)->format('F j, Y g:i A').' (Philippine time)']));
        $writer->addRow(Row::fromValues(['Generated by', $this->user->name]));
        $writer->addRow(Row::fromValues(['Each sheet holds the data of one Dashboard chart.']));
        $writer->addRow(Row::fromValues([]));

        $this->header($writer, ['Nationwide', 'Total']);
        foreach ([
            'FICs' => $national['fics'],
            'Regions with FICs' => $national['regions_with_fics'].' of '.count($this->data['regions']),
            'Products developed' => $national['products_developed'],
            'Products commercialized' => $national['products_commercialized'],
            'Commercialized (% of products developed)' => $this->percent($national['products_commercialized'], $national['products_developed']),
            'Food MSME partners (DOST FIC Focal reports)' => $national['msme_partners'],
            'Food MSME partners with LTO' => $national['msmes_with_lto'],
            'FIC equipment units listed' => $national['equipment'],
        ] as $label => $value) {
            $writer->addRow(Row::fromValues([$label, $value]));
        }
    }

    private function ficsAndProducts(Writer $writer): void
    {
        $this->regionTable($writer, [
            'FICs' => 'fics',
            'Products developed' => 'products_developed',
            'Products commercialized' => 'products_commercialized',
        ]);
    }

    private function msmePartners(Writer $writer): void
    {
        $this->regionTable($writer, [
            'Food MSME partners' => 'msme_partners',
            'MSMEs with LTO' => 'msmes_with_lto',
        ], withLtoShare: true);
    }

    private function assistanceNationwide(Writer $writer): void
    {
        $fics = $this->data['national']['fics'];
        $this->widths($writer, 42, 3);
        $this->header($writer, ['Assistance requested by MSMEs', 'FICs requesting', '% of all FICs']);

        foreach ($this->rankedAssistance() as $type) {
            $writer->addRow(Row::fromValues([$type['label'], $type['fics'], $this->percent($type['fics'], $fics)]));
        }
        $writer->addRow(Row::fromValues([]));
        $writer->addRow(Row::fromValues(["Out of {$fics} FICs. A FIC can request several types."]));
    }

    private function assistanceByRegion(Writer $writer): void
    {
        $regions = $this->data['regions'];
        $this->widths($writer, 42, count($regions) + 2, rest: 9);
        $writer->getCurrentSheet()->setSheetView((new SheetView)->withFreezeRow(2)->withFreezeColumn('B'));

        $this->header($writer, ['Assistance requested by MSMEs', ...array_column($regions, 'code'), 'All']);
        $writer->addRow(Row::fromValuesWithStyle(['FICs in the region', ...array_column($regions, 'fics'), $this->data['national']['fics']], new Style(fontItalic: true)));

        foreach ($this->rankedAssistance() as $type) {
            $writer->addRow(Row::fromValues([
                $type['label'],
                ...array_map(fn (array $r) => $r['assistance'][$type['type']] ?? 0, $regions),
                $type['fics'],
            ]));
        }
        $writer->addRow(Row::fromValues([]));
        $writer->addRow(Row::fromValues(["Each number is how many of the region's FICs requested that type. Region codes:"]));
        foreach ($regions as $region) {
            $writer->addRow(Row::fromValues([$region['code'].': '.$region['name']]));
        }
    }

    private function equipmentByRegion(Writer $writer): void
    {
        $operations = EquipmentOperation::cases();
        $utilizations = EquipmentUtilization::cases();
        $headings = [
            'Region',
            'Equipment units',
            ...array_map(fn ($s) => 'Operation: '.$s->label(), $operations),
            ...array_map(fn ($s) => 'Utilization: '.$s->label(), $utilizations),
        ];
        $this->widths($writer, 34, count($headings), rest: 18);
        $this->header($writer, $headings);

        $rows = array_map(fn (array $r) => [
            $r['name'],
            array_sum($r['equipment']['operation']),
            ...array_map(fn ($s) => $r['equipment']['operation'][$s->value] ?? 0, $operations),
            ...array_map(fn ($s) => $r['equipment']['utilization'][$s->value] ?? 0, $utilizations),
        ], $this->data['regions']);

        foreach ($rows as $row) {
            $writer->addRow(Row::fromValues($row));
        }
        $this->totalRow($writer, $rows);
    }

    private function equipmentByType(Writer $writer): void
    {
        $operations = EquipmentOperation::cases();
        $utilizations = EquipmentUtilization::cases();
        $headings = [
            'Equipment',
            'Units nationwide',
            ...array_map(fn ($s) => 'Utilization: '.$s->label(), $utilizations),
            ...array_map(fn ($s) => 'Operation: '.$s->label(), $operations),
        ];
        $this->widths($writer, 34, count($headings), rest: 18);
        $this->header($writer, $headings);

        $rows = array_map(fn (array $t) => [
            $t['name'],
            $t['total'],
            ...array_map(fn ($s) => $t['utilization'][$s->value] ?? 0, $utilizations),
            ...array_map(fn ($s) => $t['operation'][$s->value] ?? 0, $operations),
        ], $this->data['equipment_types']);

        foreach ($rows as $row) {
            $writer->addRow(Row::fromValues($row));
        }
        $this->totalRow($writer, $rows);
    }

    /**
     * Every region in the official order, one column per field, and a nationwide total row.
     *
     * @param  array<string, string>  $columns  heading => region field
     */
    private function regionTable(Writer $writer, array $columns, bool $withLtoShare = false): void
    {
        $headings = ['Region', ...array_keys($columns), ...($withLtoShare ? ['% with LTO'] : [])];
        $this->widths($writer, 34, count($headings), rest: 22);
        $this->header($writer, $headings);

        $rows = array_map(fn (array $r) => [$r['name'], ...array_map(fn (string $field) => $r[$field], array_values($columns))], $this->data['regions']);
        foreach ($rows as $row) {
            $writer->addRow(Row::fromValues($withLtoShare ? [...$row, $this->percent($row[2], $row[1])] : $row));
        }

        $totals = $this->totalRow($writer, $rows, write: ! $withLtoShare);
        if ($withLtoShare) {
            $writer->addRow(Row::fromValuesWithStyle([...$totals, $this->percent($totals[2], $totals[1])], new Style(fontBold: true)));
        }
    }

    /**
     * "Nationwide" plus the sum of every numeric column.
     *
     * @param  list<list<mixed>>  $rows
     * @return list<mixed>
     */
    private function totalRow(Writer $writer, array $rows, bool $write = true): array
    {
        $width = count($rows[0] ?? ['']);
        $totals = ['Nationwide', ...array_map(fn (int $i) => array_sum(array_column($rows, $i)), range(1, max(1, $width - 1)))];
        if ($write) {
            $writer->addRow(Row::fromValuesWithStyle($totals, new Style(fontBold: true)));
        }

        return $totals;
    }

    /**
     * Same order as the chart: most requested first, "Other" last.
     *
     * @return list<array{type: string, label: string, fics: int}>
     */
    private function rankedAssistance(): array
    {
        $types = $this->data['assistance'];
        usort($types, fn (array $a, array $b) => [$a['type'] === 'other', -$a['fics']] <=> [$b['type'] === 'other', -$b['fics']]);

        return $types;
    }

    /**
     * @param  list<string>  $headings
     */
    private function header(Writer $writer, array $headings): void
    {
        $writer->addRow(Row::fromValuesWithStyle($headings, EntryReport::headerStyle()));
    }

    private function widths(Writer $writer, float $first, int $columns, float $rest = 18): void
    {
        $sheet = $writer->getCurrentSheet();
        $sheet->setColumnWidth($first, 1);
        if ($columns > 1) {
            $sheet->setColumnWidthForRange($rest, 2, $columns);
        }
    }

    private function percent(int $part, int $whole): string
    {
        return $whole > 0 ? round($part / $whole * 100).'%' : 'n/a';
    }
}
